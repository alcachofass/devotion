static const int cgameCvarDescriptionCount = sizeof( cgameCvarDescriptions ) / sizeof( cgameCvarDescriptions[0] );

static const char *BG_LookupCvarDescription( const cvarDesc_t *table, int count, const char *name ) {
	int i;

	if ( !name || !name[0] ) {
		return NULL;
	}

	for ( i = 0; i < count; i++ ) {
		if ( !Q_stricmp( table[i].name, name ) ) {
			return table[i].description;
		}
	}

	return NULL;
}

const char *BG_GameCvarDescription( const char *name ) {
	return BG_LookupCvarDescription( gameCvarDescriptions, gameCvarDescriptionCount, name );
}

const char *BG_CgameCvarDescription( const char *name ) {
	return BG_LookupCvarDescription( cgameCvarDescriptions, cgameCvarDescriptionCount, name );
}

void BG_RegisterGameCvarDescriptions( void ) {
	int i;
	const char *desc;

	BG_TrapExt_Init();

	for ( i = 0; i < gameCvarDescriptionCount; i++ ) {
		desc = gameCvarDescriptions[i].description;
		if ( desc && desc[0] ) {
			BG_RegisterCvarDescription( gameCvarDescriptions[i].name, desc );
		}
	}
}

void BG_RegisterCgameCvarDescriptions( void ) {
	int i;
	const char *desc;

	BG_TrapExt_Init();

	for ( i = 0; i < cgameCvarDescriptionCount; i++ ) {
		desc = cgameCvarDescriptions[i].description;
		if ( desc && desc[0] ) {
			BG_RegisterCvarDescription( cgameCvarDescriptions[i].name, desc );
		}
	}
}
